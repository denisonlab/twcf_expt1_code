function exitNow = expt_runBlock_instructions(w, p, b, setup)
% exitNow = expt_runBlock_instructions(w, p, b, setup)

% kbText = ['Keyboard reminder:\n' ...
%           '1 --> vertical oval, saw shape\n', ...
%           '2 --> vertical oval, saw a figure but not its shape\n', ...
%           '3 --> vertical oval, did not see a figure\n', ...
%           '8 --> horizontal oval, did not see a figure\n', ...
%           '9 --> horizontal oval, saw a figure but not its shape\n', ...
%           '0 --> horizontal oval, saw shape\n\n'];
if setup.isPractice || setup.isMainExpt || setup.isValidation || setup.isPiloting
        kbText = ['Keyboard reminder:\n' ...
            '1st response\n' ... 
            '1 --> counterclockwise from vertical, more visible than reference\n', ...
            '2 --> counterclockwise from vertical, less visible than reference\n', ...
            '9 --> clockwise from vertical, less visible than reference\n', ...
            '0 --> clockwise from vertical, more visible than reference'];
elseif setup.isTraining || setup.isThresholding 
        kbText = ['Keyboard reminder:\n' ...
            '1 --> counterclockwise from vertical\n', ...
            '0 --> clockwise from vertical\n'];
end

if setup.buttons==2
    kbText = [kbText '\n\n'...
        '2nd response\n'...
        '3 --> guessed the direction of the tilt\n'...
        '8 --> saw the direction of the tilt\n'];
else
    kbText = [kbText '\n'];
end

prompt =  '__________\nPress any key to continue.';


%% practice instructions

if setup.isPractice
    
    switch setup.practiceStage

        % initial practice
        case 2

            prepText = ['SLOWED DOWN PRACTICE\n\nIn the following trials, the stimuli will be slowed down so that ' ...
                        'you can get used to doing the task. There will be no time limit for entering each response.\n\n' ...
                        'You have not yet completed the training stage where you will learn the reference visibility. ' ...
                        'So during these practice trials, you can just '...
                        'report visibility according to whether the grating pop-out appears strong or weak.\n\n' ...
                        'After entering your response, text will appear on the screen ' ...
                        'informing you what the stimulus at the cued location was, and what ' ...
                        'your response was.\n\n' ...
                        'You can use this feedback in two ways:\n' ...
                        '(1) double check that what the computer "thinks" you responded ' ...
                        'matches with what you intended to respond.\n' ...
                        '(2) find out whether your response accurately corresponds to what ' ...
                        'the stimulus was.\n\n'];

        % practice w/ auditory FB
        case 3

            prepText = ['FULL SPEED PRACTICE WITH FEEDBACK\n\nIn the following trials, the stimuli will be shown at ' ...
                        'full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                        ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                        'as possible. Use this practice as a chance to get used to the pacing of the stimuli ' ...
                        'and the response time limit.\n\n' ...
                        'You have not yet completed the training stage where you will learn the reference visibility. ' ...
                        'So during these practice trials, you can just '...
                        'report visibility according to whether the grating contrast appeared strong or weak.\n\n' ...
                        'After entering your response, you will get auditory feedback about ' ...
                        'the tilt judgment. The auditory feedback works as follows:\n' ...
                        '* high pitched tone -> the tilt judgment was correct\n' ...
                        '* low pitched tone -> the tilt judgment was incorrect\n\n' ];

        % practice w/out auditory FB
        case 4

            prepText = ['FULL SPEED PRACTICE WITHOUT FEEDBACK\n\nIn the following trials, the stimuli will be shown at ' ...
                        'full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                        ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                        'as possible. Use this practice as a chance to get used to the pacing of the stimuli ' ...
                        'and the response time limit.\n\n' ...
                        'You have not yet completed the training stage where you will learn the reference visibility. ' ...
                        'So during these practice trials, you can just '...
                        'report visibility according to whether the grating contrast appeared strong or weak.\n\n' ...
                        'There will be no performance feedback for these trials.\n\n' ...
                        'These trials are identical to the trials you will be doing in the main experiment.\n\n'];

    end
    
%% thresholding instructions

elseif setup.isTraining

    prepText = ['REFERENCE TRAINING STAGE\n\n' ...
                'In the following trials, you will be performing the reference training stage of the experiment.\n\n' ...
                'During training, gratings indicated by the postcue will have about the same visibility. ' ...
                '(As a reminder, "visibility" refers to how strongly the grating pops out.) ' ...
                'The main purpose of the training stage is for you to note and learn how visible the postcued ' ...
                'gratings appear. This learned level of visibility will be your reference for making visibility ' ...
                'judgments in subsequent parts of the experiment.\n\n' ...
                'During reference training,\n' ...
                '- you ONLY have to report the tilt of the grating (counterclockwise or clockwise from vertical)\n' ...
                '- you will NOT have to report grating pop-out visibility\n' ...
                '- you will NOT have to report whether you guessed the tilt of the grating or saw it\n'...
                '- you will always be cued to attend to all 4 quadrants (all 4 cues flash white on every trial)\n\n' ...
                'The stimuli will be shown at full speed. The time limit for entering your response is ' num2str(p.timing.postcueDur_inSecs) ...
                ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                'as possible.\n\n' ...
                'There will be no performance feedback for these trials.\n\n'];
    
elseif setup.isThresholding
    
    prepText = ['TILT TRAINING STAGE\n\n' ...
                'In the following trials, it will get harder to determine the grating tilt.\n' ...
                'Continue to do your best!\n\n' ...
                'During this stage,\n' ...
                '- you ONLY have to report the tilt of the grating (counterclockwise or clockwise from vertical)\n' ...
                '- you will NOT have to report grating pop-out visibility\n' ...
                '- you will NOT have to report whether you guessed the tilt of the grating or saw it\n'...
                '- you will always be cued to attend to all 4 quadrants (all 4 cues flash white on every trial)\n\n' ...
                'The stimuli will be shown at full speed. The time limit for entering your response is ' num2str(p.timing.postcueDur_inSecs) ...
                ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                'as possible.\n\n' ...
                'There will be no performance feedback for these trials.\n\n'];

%% validation instructions 

elseif setup.isValidation

    prepText = ['FULL RESPONSE TRAINING STAGE\n\n' ...
        'In the following trials, you will be performing the final training stage.\n\n' ...
        'You will always be cued to attend to all 4 quadrants (all 4 cues will flash white).\n\n' ...
        'Response entry\n' ...
        'When responding to the postcue, you will first use a single keypress to indicate BOTH the\n' ...
        '- grating tilt (counterclockwise or clockwise from vertical)\n' ... 
        '- grating visibility (more or less visible than the reference you learned earlier)\n\n' ...
        'Then, you will use a second keypress to indicate\n' ...
        '- whether you guessed the tilt of the grating or saw it\n\n' ...
        'The time limit for entering each response is ' num2str(p.timing.postcueDur_inSecs) ...
        ' seconds. Remember that it''s important to enter your response on as many trials ' ...
        'as possible. ' ...
        'There will be no performance feedback for these trials.\n\n']; 


%% piloting instructions
    
elseif setup.isPiloting

    prepText = ['PILOTING\n\nIn the following trials, you will be performing piloting. ' ...
        'The stimuli will be shown at full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ...
        ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
        'as possible.\n\n' ...
        'There will be no performance feedback for these trials.\n\n' ...
        'You will receive breaks every ' num2str(b.nTrialsPerBlock) ' trials. During these breaks, ' ...
        'you can rest for as long as you need to. Overall, there will be ' num2str(b.nBlocks) ' blocks ' ...
        'of trials separated by break periods.\n\n' ...
        'This is a special block of trials where you will always be cued to attend to all 4 quadrants ' ...
        '(all 4 cues will flash white on every trial).\n\n'];

%% main experiment instructions

elseif setup.isMainExpt

    prepText = ['MAIN EXPERIMENT\n\nIn the following trials, you will be performing the main experiment. ' ...
            'The time limit for entering each response is ' num2str(p.timing.postcueDur_inSecs) ... 
            ' seconds. There will be no performance feedback for these trials. ' ...
            'You will receive breaks every ' num2str(b.nTrialsPerBlock) ' trials. ' ...
            'Overall, there will be ' num2str(b.nBlocks) ' blocks ' ...
            'of trials separated by breaks, during which you can rest for as long as you need to.\n\n' ...
            'Attention cues\n'...
            'Most of the time you will be cued to attend to one quadrant (one cue will flash white). ' ...
            'Sometimes you will be cued to attend to all 4 quadrants (all 4 cues will flash white).\n\n'...
            'Response entry\n' ...
            'When responding to the postcue, you will first use a single keypress to indicate BOTH the\n' ...
            '- grating tilt (counterclockwise or clockwise from vertical)\n' ...
            '- grating visibility (more or less visible than the reference you learned earlier)\n\n' ...
            'Then, you will use a second keypress to indicate\n' ...
            '- whether you guessed the tilt of the grating or saw it\n\n'];

elseif setup.takeScreenshot
    
    prepText = ['SCREENSHOT\n\nTakes a screenshot of the trial sequence.\n\n']; 

end

prepText = [prepText kbText];

% show main text
DrawFormattedText(w, prepText, p.text.sx, p.text.sy, 0, p.text.wrapat);
Screen('Flip', w);

% after a delay, show prompt to move on
WaitSecs(5);

[nx, ny] = DrawFormattedText(w, prepText, p.text.sx, p.text.sy, 0, p.text.wrapat);
DrawFormattedText(w, prompt, p.text.sx, ny, 0, p.text.wrapat);
Screen('Flip', w);

KbWait(p.kb.kbNum);

% check for exit key
[k, secs, key] = KbCheck(p.kb.kbNum);
if strcmp(KbName(key), p.kb.exitKey)
    exitNow = 1; 
else
    exitNow = 0;
end