function exitNow = expt_runBlock_instructions(w, p, b, setup)
% exitNow = expt_runBlock_instructions(w, p, b, setup)

kbText = ['Keyboard reminder:\n' ...
          '1 --> vertical oval, saw shape\n', ...
          '2 --> vertical oval, saw a figure but not its shape\n', ...
          '3 --> vertical oval, did not see a figure\n', ...
          '8 --> horizontal oval, did not see a figure\n', ...
          '9 --> horizontal oval, saw a figure but not its shape\n', ...
          '0 --> horizontal oval, saw shape\n\n'];
      
prompt =  '__________\nPress any key to continue.';


%% practice instructions

if setup.isPractice 
    
    switch setup.practiceStage

        % initial practice
        case 2

            prepText = ['SLOWED DOWN PRACTICE\n\nIn the following trials, the stimuli will be slowed down so that ' ...
                        'you can get used to doing the task. The time limit for entering ' ...
                        'a response will also be turned off.\n\n' ...
                        'After entering your response, text will appear on the screen ' ...
                        'informing you what the stimulus at the cued location was, and what ' ...
                        'your response was.\n\n' ...
                        'You can use this feedback in two ways:\n' ...
                        '(1) double check that what the computer "thinks" you responded ' ...
                        'matches with what you intended to respond.\n' ...
                        '(2) find out whether your response accurately corresponds to what ' ...
                        'the stimulus was.\n\n'];

        % practice w/ auditory FB
        case 3

            prepText = ['FULL SPEED PRACTICE WITH FEEDBACK\n\nIn the following trials, the stimuli will be shown at ' ...
                        'full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                        ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                        'as possible. Use this practice as a chance to get used to the pacing of the stimuli ' ...
                        'and the response time limit.\n\n' ...
                        'After entering your response, you will get auditory feedback about ' ...
                        'the orientation judgment. The auditory feedback works as follows:\n' ...
                        '* high pitched tone -> the vertical / horizontal judgment was correct\n' ...
                        '* low pitched tone -> the vertical / horizontal judgment was incorrect\n\n' ...
                        'On trials where there was no oval present, you will receive random auditory feedback.\n\n' ...
                        'There is no feedback about the seen / not seen report. That''s because we''re ' ...
                        'interested in your subjective experience (what you actually perceived) moreso than ' ...
                        'how your experience corresponds to the objective presence or absence of the oval.\n\n'];

        % practice w/out auditory FB
        case 4

            prepText = ['FULL SPEED PRACTICE WITHOUT FEEDBACK\n\nIn the following trials, the stimuli will be shown at ' ...
                        'full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                        ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                        'as possible. Use this practice as a chance to get used to the pacing of the stimuli ' ...
                        'and the response time limit.\n\n' ...
                        'There will be no performance feedback for these trials.\n\n' ...
                        'These trials are identical to the trials you will be doing in the main experiment.\n\n'];

    end
    
%% thresholding instructions
    
elseif setup.isThresholding
    
    prepText = ['MAIN EXPERIMENT\n\nIn the following trials, you will be performing the main experiment. ' ...
                'The stimuli will be shown at full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                'as possible.\n\n' ...
                'There will be no performance feedback for these trials.\n\n' ...
                'You will receive breaks every ' num2str(b.nTrialsPerBlock) ' trials. During these breaks, ' ...
                'you can rest for as long as you need to. Overall, there will be ' num2str(b.nBlocks) ' blocks ' ...
                'of trials separated by break periods.\n\n' ...
                'This is a special block of trials where you will always be cued to attend to all 4 quadrants ' ...
                '(all 4 cues will flash white on every trial).\n\n'];

            
%% main experiment instructions

elseif setup.isMainExpt

    prepText = ['MAIN EXPERIMENT\n\nIn the following trials, you will be performing the main experiment. ' ...
                'The stimuli will be shown at full speed. The time limit for entering a response is ' num2str(p.timing.postcueDur_inSecs) ... 
                ' seconds. Remember that it''s important to enter your responses on as many trials ' ...
                'as possible.\n\n' ...
                'There will be no performance feedback for these trials.\n\n' ...
                'You will receive breaks every ' num2str(b.nTrialsPerBlock) ' trials. During these breaks, ' ...
                'you can rest for as long as you need to. Overall, there will be ' num2str(b.nBlocks) ' blocks ' ...
                'of trials separated by break periods.\n\n' ...
                'Most of the time you will be cued to attend to one quadrant (one cue will flash white). ' ...
                'Sometimes you will be cued to attend to all 4 quadrants (all 4 cues will flash white).\n\n'];

elseif setup.takeScreenshot
    prepText = ['SCREENSHOT']; 
    
end

prepText = [prepText kbText];

% show main text
DrawFormattedText(w, prepText, p.text.sx, p.text.sy, 0, p.text.wrapat);
Screen('Flip', w);

% after a delay, show prompt to move on
WaitSecs(5);

[nx, ny] = DrawFormattedText(w, prepText, p.text.sx, p.text.sy, 0, p.text.wrapat);
DrawFormattedText(w, prompt, p.text.sx, ny, 0, p.text.wrapat);
Screen('Flip', w);

KbWait(p.kb.kbNum);

% check for exit key
[k, secs, key] = KbCheck(p.kb.kbNum);
if strcmp(KbName(key), p.kb.exitKey)
    exitNow = 1; 
else
    exitNow = 0;
end